/** Latin letters of the Ukrainian ones (official transliteration of 2010), for the search. */
const LATIN = {
  а: 'a',
  б: 'b',
  в: 'v',
  г: 'h',
  ґ: 'g',
  д: 'd',
  е: 'e',
  є: 'ie',
  ж: 'zh',
  з: 'z',
  и: 'y',
  і: 'i',
  ї: 'i',
  й: 'i',
  к: 'k',
  л: 'l',
  м: 'm',
  н: 'n',
  о: 'o',
  п: 'p',
  р: 'r',
  с: 's',
  т: 't',
  у: 'u',
  ф: 'f',
  х: 'kh',
  ц: 'ts',
  ч: 'ch',
  ш: 'sh',
  щ: 'shch',
  ь: '',
  ю: 'iu',
  я: 'ia',
  '’': '',
  "'": '',
};

/** Lower case, Latin letters, no accent nor apostrophe: what the search compares. */
export function fold(text) {
  return [...String(text ?? '').toLowerCase()]
    .map((c) => LATIN[c] ?? c)
    .join('')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '');
}

/** UID -> { uk, en? } */
export const LOCATIONS = new Map([
  ...OBLASTS.map(([uid, uk, en]) => [uid, { uk, en }]),
  ...RAIONS.map(([uid, uk]) => [uid, { uk }]),
]);

/** The name of a location: Ukrainian, and English when known. */
export function locationName(uid) {
  const known = LOCATIONS.get(uid);
  if (!known) {
    return `Location ${uid}`;
  }
  return known.en ? `${known.uk} (${known.en})` : known.uk;
}

/** The locations whose name holds every word of the query (Cyrillic or Latin), at most `limit`. */
export function searchLocations(query, limit = 15) {
  const words = fold(query)
    .split(/[\s,.;-]+/)
    .filter((w) => w.length >= 2);
  if (words.length === 0) {
    return [];
  }
  const found = [];
  for (const [uid, names] of LOCATIONS) {
    const haystack = `${fold(names.uk)} ${fold(names.en ?? '')}`;
    if (words.every((w) => haystack.includes(w))) {
      found.push({ uid, name: locationName(uid) });
    }
  }
  return found.slice(0, limit);
}
